"""Dependency trust boundary: format checks, not claims of MCP compatibility."""
from __future__ import annotations

from importlib import util
from pathlib import Path
import sys

import pytest

ROOT = Path(__file__).resolve().parents[1]
_spec = util.spec_from_file_location("vater_dependency_lock", ROOT / "scripts" / "check_dependency_lock.py")
assert _spec is not None and _spec.loader is not None
lock = util.module_from_spec(_spec)
sys.modules[_spec.name] = lock
_spec.loader.exec_module(lock)

SAMPLE_SHA = "a" * 64


def sample(*, mcp: str = "2.3.0") -> str:
    packages = {"mcp": mcp, "anyio": "4.8.0", "pytest": "8.3.5",
                "pydantic": "2.11.2", "jsonschema": "4.25.1"}
    return "\n".join(f"{k}=={v} \\\n    --hash=sha256:{SAMPLE_SHA}" for k, v in packages.items()) + "\n"


def test_valid_generated_like_lock():
    items = lock.validate_lock("# generated by uv\n" + sample())
    assert len(items) == 5 and items["mcp"] == "2.3.0"


def test_hash_on_same_line_is_accepted():
    inline = sample().replace("mcp==2.3.0 \\\n    --hash=sha256:" + SAMPLE_SHA,
                              "mcp==2.3.0 --hash=sha256:" + SAMPLE_SHA)
    assert lock.validate_lock(inline)["mcp"] == "2.3.0"


def test_repeated_artifact_hashes_allowed():
    source = sample().replace("mcp==2.3.0 \\\n", "mcp==2.3.0 \\\n    --hash=sha256:" + "b" * 64 + " \\\n")
    assert lock.validate_lock(source)["mcp"] == "2.3.0"


@pytest.mark.parametrize("bad,rule", [
    ("", "LOCK-EMPTY"),
    (sample(mcp="2.2.0"), "LOCK-WRONG-MCP-VERSION"),
    (sample().replace("anyio==4.8.0 \\\n    --hash=sha256:" + SAMPLE_SHA, "anyio>=4"),
     "LOCK-NONPINNED-OR-UNSAFE-REQUIREMENT"),
    (sample().replace("jsonschema==4.25.1 \\\n    --hash=sha256:" + SAMPLE_SHA, ""),
     "LOCK-MISSING-REQUIRED-GROUP"),
    (sample() + "mcp==2.3.0 \\\n    --hash=sha256:" + SAMPLE_SHA + "\n", "LOCK-DUPLICATE-PACKAGE"),
    (sample().replace("--hash=sha256:" + SAMPLE_SHA, "--hash=sha256:oops", 1),
     "LOCK-MISSING-OR-INVALID-HASH"),
    (sample().replace("mcp==2.3.0 \\\n    --hash=sha256:" + SAMPLE_SHA, "mcp==2.3.0"),
     "LOCK-MISSING-OR-INVALID-HASH"),
    (sample().replace("mcp==2.3.0", "-e ./src"), "LOCK-NONPINNED-OR-UNSAFE-REQUIREMENT"),
    (sample().replace("mcp==2.3.0", "mcp @ https://example.com/mcp.whl"),
     "LOCK-NONPINNED-OR-UNSAFE-REQUIREMENT"),
    (sample() + "-r other.txt\n", "LOCK-NONPINNED-OR-UNSAFE-REQUIREMENT"),
    (sample() + "--extra-index-url https://example.com\n", "LOCK-NONPINNED-OR-UNSAFE-REQUIREMENT"),
    (sample() + "mcp==2.3.0 \\\n", "LOCK-UNFINISHED-CONTINUATION"),
])
def test_lock_rejection(bad, rule):
    with pytest.raises(lock.LockRejected) as exc:
        lock.validate_lock(bad)
    assert exc.value.code == rule


def test_name_normalization_blocks_duplicate_alias():
    data = sample() + "Py_Test==8.3.5 \\\n    --hash=sha256:" + SAMPLE_SHA + "\n"
    assert lock.validate_lock(data)["py-test"] == "8.3.5"
    with pytest.raises(lock.LockRejected, match="LOCK-DUPLICATE-PACKAGE"):
        lock.validate_lock(sample() + "MCP==2.3.0 \\\n    --hash=sha256:" + SAMPLE_SHA + "\n")


def test_command_fails_if_lock_missing(tmp_path, capsys):
    assert lock.main([str(tmp_path / "absent.lock")]) == 1
    assert "LOCK-UNAVAILABLE" in capsys.readouterr().out


def test_command_passes_only_with_valid_lock(tmp_path, capsys):
    path = tmp_path / "requirements-py313.lock"
    path.write_text(sample(), encoding="utf-8")
    assert lock.main([str(path)]) == 0
    assert '"state": "validated"' in capsys.readouterr().out


def test_invalid_utf8_rejected(tmp_path):
    path = tmp_path / "bad.lock"
    path.write_bytes(b"\xff")
    with pytest.raises(lock.LockRejected, match="LOCK-INVALID-ENCODING"):
        lock.verify_file(path)


def test_file_size_limit(tmp_path):
    path = tmp_path / "large.lock"
    path.write_bytes(b"x" * 1_048_577)
    with pytest.raises(lock.LockRejected, match="LOCK-TOO-LARGE"):
        lock.verify_file(path)
