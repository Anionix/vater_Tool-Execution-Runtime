#!/usr/bin/env python3
"""task.operations.004: where each Python dependency comes from, and at which version.

  python scripts/dependency_sources.py           # print the record
  python scripts/dependency_sources.py --write   # update docs/dependency_sources.json

The record is derived from requirements-py313.lock (version, artifact hashes
and the "via" chain that adopted each package) and from every dependency
install in .github/workflows, each classified as hash-locked, a pinned tool,
or a diagnostic install of unpinned versions that never builds a release.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
RECORD = ROOT / "docs" / "dependency_sources.json"
DIRECT = {"anyio": ">=4,<5", "pytest": ">=8", "jsonschema": ">=4", "pydantic": ">=2", "mcp": "==2.3.0"}


def parse_lock(text: str) -> list[dict]:
    packages, current, via_block = [], None, False
    for line in text.splitlines():
        match = re.match(r"^([A-Za-z0-9][A-Za-z0-9_.-]*)==(\S+)", line)
        if match:
            current = {"name": match.group(1), "version": match.group(2), "hashes": 0, "adopted_via": []}
            packages.append(current)
            via_block = False
            continue
        if current is None:
            continue
        current["hashes"] += len(re.findall(r"--hash=sha256:[0-9a-f]{64}", line))
        stripped = line.strip()
        if stripped.startswith("# via"):
            rest = stripped[len("# via"):].strip()
            if rest:
                current["adopted_via"].append(rest)
            via_block = not rest
        elif via_block and stripped.startswith("#   "):
            current["adopted_via"].append(stripped[4:].strip())
    return packages


def classify(command: str) -> tuple[str, str]:
    if "--require-hashes" in command and "requirements-py313.lock" in command:
        return "hash_locked", "Installs exactly the reviewed lock, every artifact checked against its SHA-256."
    if "--require-hashes" in command and "requirements-build.lock" in command:
        return "hash_locked", "Installs exactly the reviewed build backend, checked against its SHA-256."
    if re.fullmatch(r"python -m pip install uv==\d+(\.\d+)*", command):
        return "tool_pinned", "The resolver itself, pinned to an exact version, used only to produce a lock candidate."
    return ("diagnostic_unpinned", "Offline or diagnostic tests against the newest allowed versions; never used to "
            "build or release, and the release jobs install the lock.")


def workflow_installs(root: Path = ROOT) -> list[dict]:
    found = []
    for path in sorted((root / ".github" / "workflows").glob("*.yml")):
        for line in path.read_text(encoding="utf-8").splitlines():
            if re.search(r"\b(pip install|uv pip (sync|install))\b", line):
                command = line.split("run:", 1)[-1].strip()
                kind, reason = classify(command)
                found.append({"workflow": path.name, "command": command, "kind": kind, "reason": reason})
    return found


def build(root: Path = ROOT) -> dict:
    lock = (root / "requirements-py313.lock").read_text(encoding="utf-8")
    return {
        "_comment": ["task.operations.004: where each Python dependency comes from and at which version.",
                     "Generated by scripts/dependency_sources.py from requirements-py313.lock and .github/workflows;",
                     "tests/test_dependency_sources.py fails when this record and its sources disagree."],
        "lock": "requirements-py313.lock",
        "lock_sha256": hashlib.sha256(lock.encode("utf-8")).hexdigest(),
        "index": ("https://pypi.org/simple, the default index of uv and pip. The lock names no other index, "
                  "find-links, local path, VCS or URL source, and every artifact is pinned by SHA-256."),
        "resolver": "uv 0.10.0 in .github/workflows/dependency-lock-candidate.yml, for CPython 3.13 on x86-64 Linux",
        "direct_requirements": DIRECT,
        "packages": parse_lock(lock),
        "build_requirements": {"lock": "requirements-build.lock",
                               "packages": parse_lock((root / "requirements-build.lock").read_text(encoding="utf-8"))},
        "installs": workflow_installs(root),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    text = json.dumps(build(), indent=1) + "\n"
    if args.write:
        RECORD.write_text(text, encoding="utf-8")
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
